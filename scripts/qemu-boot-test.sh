#!/usr/bin/env bash
# Full-system boot test: boot the Buildroot image for one architecture in
# qemu-system, wait for the init script to run edgeprobe, and gate on the
# marker it prints on the serial console.
#
# Usage: scripts/qemu-boot-test.sh <rust-target-triple> [images-dir]
#   images-dir defaults to br-images/<arch> (output/images of the Buildroot job)
# shellcheck source=scripts/common.sh
source "$(dirname "$0")/common.sh"

TARGET="${1:?usage: qemu-boot-test.sh <target> [images-dir]}"
require_target "$TARGET"
ARCH="${ARCH_OF[$TARGET]}"
IMAGES="${2:-$REPO_ROOT/br-images/$ARCH}"
TIMEOUT="${BOOT_TIMEOUT:-180}"
LOG="$DIST_DIR/boot-$ARCH.log"

[[ -x "$IMAGES/start-qemu.sh" ]] || die "no start-qemu.sh in $IMAGES (run the Buildroot image job first)"
mkdir -p "$DIST_DIR"

log "booting $ARCH image (timeout ${TIMEOUT}s), console -> $LOG"
# start-qemu.sh is generated by Buildroot for its qemu_* defconfigs.
# 'serial-only' = no graphics, console on stdio.
set +e
( cd "$IMAGES" && timeout "$TIMEOUT" ./start-qemu.sh serial-only ) </dev/null >"$LOG" 2>&1 &
QPID=$!

RESULT=timeout
for _ in $(seq 1 "$TIMEOUT"); do
  if grep -q "EDGEPROBE_BOOT_OK" "$LOG"; then RESULT=ok; break; fi
  if grep -q "EDGEPROBE_BOOT_FAIL" "$LOG"; then RESULT=fail; break; fi
  if grep -qE "Kernel panic|not syncing" "$LOG"; then RESULT=panic; break; fi
  kill -0 "$QPID" 2>/dev/null || break
  sleep 1
done
pkill -P "$QPID" 2>/dev/null; kill "$QPID" 2>/dev/null; wait "$QPID" 2>/dev/null
set -e

grep -E "EDGEPROBE|\"status\"" "$LOG" || true
case "$RESULT" in
  ok)      log "OK: $ARCH booted and edgeprobe reported healthy" ;;
  fail)    die "edgeprobe ran but reported unhealthy on $ARCH" ;;
  panic)   die "kernel panic on $ARCH (see $LOG)" ;;
  *)       tail -n 40 "$LOG" >&2; die "no boot marker within ${TIMEOUT}s on $ARCH" ;;
esac
